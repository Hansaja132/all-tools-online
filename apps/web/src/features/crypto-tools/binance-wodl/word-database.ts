/**
 * Builds candidate words list for the given length using ONLY
 * this week's active theme words — no base pool, no past themes.
 */
export function getCandidateWordsForLength(
  length: number,
  activeTheme?: WodlTheme,
  allThemes: WodlTheme[] = [],
): CandidateWord[] {
  // Only use this week's theme words — ignore MASTER_CANDIDATE_WORDS and allThemes
  const thisWeekWords = activeTheme?.words?.[length as 3 | 4 | 5 | 6 | 7 | 8] || [];

  const candidates: CandidateWord[] = thisWeekWords.map((w) => ({
    word: w.trim().toUpperCase(),
    isConfirmed: true,
  }));

  // Sort alphabetically
  candidates.sort((a, b) => a.word.localeCompare(b.word));

  return candidates;
}
