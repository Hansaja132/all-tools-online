/**
 * Builds candidate words list for the given length, marking confirmed words
 * based on the active theme and any custom themes.
 */
export function getCandidateWordsForLength(
  length: number,
  activeTheme?: WodlTheme,
  allThemes: WodlTheme[] = []
): CandidateWord[] {
  const baseWords = MASTER_CANDIDATE_WORDS[length] || [];

  // Collect theme words for this length
  const confirmedSet = new Set<string>();
  if (activeTheme?.words?.[length as 3 | 4 | 5 | 6 | 7 | 8]) {
    activeTheme.words[length as 3 | 4 | 5 | 6 | 7 | 8].forEach((w) =>
      confirmedSet.add(w.trim().toUpperCase())
    );
  }

  // Also harvest words from all themes if not already in base
  const allWordSet = new Set<string>(baseWords);
  allThemes.forEach((t) => {
    const list = t.words?.[length as 3 | 4 | 5 | 6 | 7 | 8];
    if (list) {
      list.forEach((w) => allWordSet.add(w.trim().toUpperCase()));
    }
  });

  // Convert to CandidateWord array
  const candidates: CandidateWord[] = Array.from(allWordSet).map((word) => ({
    word,
    isConfirmed: confirmedSet.has(word),
  }));

  // Sort alphabetically
  candidates.sort((a, b) => a.word.localeCompare(b.word));

  return candidates;
}
